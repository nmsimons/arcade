test('styled picker opens above a narrow inspector and remains usable with forced colors', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 }); await open(page)
  await page.getByRole('tab', { name: 'Object', exact: true }).click()
  const picker = page.getByRole('combobox', { name: 'Selected object' })
  await picker.click()
  const menu = page.getByRole('listbox', { name: 'Selected object' })
  const control = await picker.boundingBox(), popup = await menu.boundingBox()
  expect(popup.y + popup.height).toBeLessThanOrEqual(control.y)
  for (const option of await menu.getByRole('option').all()) await expect(option).toBeInViewport()
  await page.screenshot({ path: info.outputPath('styled-picker-narrow.png') })
  await menu.getByRole('option', { name: 'Entrance door', exact: true }).click()
  await expect(picker).toHaveText('Entrance door')
  await page.emulateMedia({ forcedColors: 'active' })
  await picker.press('Enter'); await picker.press('End')
  await expect(menu.getByRole('option', { name: 'Exit door', exact: true })).toHaveAttribute('data-active', 'true')
  await page.screenshot({ path: info.outputPath('styled-picker-forced-colors.png') })
  await picker.press('Escape'); await expect(picker).toHaveText('Entrance door')
})
