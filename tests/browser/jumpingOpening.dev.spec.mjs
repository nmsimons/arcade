import { readFileSync } from 'node:fs'
import { test, expect } from './helpers/test.mjs'
import { finishJumpingEntrance, installBuiltInFixtures, useLevelFixtures, selectBuilderObject, selectBuilderOption, saveTestLevel, reopenTestLevel } from './helpers/jumpingLevels.mjs'

const wake = JSON.parse(readFileSync(new URL('../../public/levels/jumping/Wake.jump-level.json', import.meta.url), 'utf8'))
const next = JSON.parse(readFileSync(new URL('../../public/levels/jumping/LAB1.jump-level.json', import.meta.url), 'utf8'))

test('Wake preserves its full-speed running stride after keyboard walking', async ({ page }, info) => {
  test.setTimeout(90_000)
  await page.setViewportSize({ width: 960, height: 600 })
  await useLevelFixtures(page, [wake])
  await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') })
  await page.goto('/lab?motionDebug=1')
  const play = page.getByRole('button', { name: 'Play Wake', exact: true })
  await expect(play).toBeEnabled()
  await page.clock.pauseAt(new Date('2026-01-01T01:00:00Z'))
  await play.click()
  await expect(page.getByRole('dialog', { name: 'Preparing level', exact: true })).toHaveCount(0)
  await page.clock.runFor(160)
  await expect(page.locator('.jumping-state')).toHaveText('Waking up')
  await finishJumpingEntrance(page)
  await page.keyboard.down('Shift'); await page.keyboard.down('ArrowRight')
  await page.clock.runFor(1800)
  await page.screenshot({ path: info.outputPath('wake-walking.png') })
  const walking = await page.evaluate(() => window.jumpingMotion.read().recent.at(-1))
  expect(walking.vx).toBeCloseTo(125)
  expect(walking.signals.grounded).toBe(true)
  await page.keyboard.up('Shift'); await page.clock.runFor(300)
  const start = await page.evaluate(() => window.jumpingMotion.read().recent.at(-1).time)
  await page.clock.runFor(1200)
  const jogging = await page.evaluate(start => window.jumpingMotion.read().recent.filter(s => s.time > start), start)
  let landings = 0
  for (let i = 1; i < jogging.length; i++) landings += jogging[i].contacts.feet.filter((foot, j) => foot.planted && !jogging[i - 1].contacts.feet[j].planted).length
  expect(jogging.length).toBeGreaterThan(120)
  expect(jogging.at(-1).vx).toBeCloseTo(410)
  expect(landings).toBeGreaterThanOrEqual(8)
  expect(landings).toBeLessThanOrEqual(10)
  expect(jogging.filter(s => s.contacts.feet.every(foot => !foot.planted)).length / jogging.length).toBeGreaterThan(.3)
  const separation = Math.max(...jogging.map(s => Math.abs(s.points[8][0] - s.points[10][0])))
  expect(separation).toBeGreaterThan(38); expect(separation).toBeLessThan(42)
  await page.screenshot({ path: info.outputPath('wake-running.png') })
  await page.keyboard.up('ArrowRight')
})

test('Wake pauses and restarts its awakening, completes with normal keys, and remembers an untimed finish', async ({ page }, info) => {
  // The staged night lighting and full route are rendered in software on CI.
  test.setTimeout(180000)
  await page.setViewportSize({ width: 960, height: 600 })
  await useLevelFixtures(page, [wake, next])
  await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') })
  await page.goto('/lab')
  const card = page.getByRole('button', { name: 'Level 1: Wake', exact: true })
  await expect.poll(() => card.locator('canvas').evaluate(c => c.width)).toBeGreaterThan(1)
  await page.clock.pauseAt(new Date('2026-01-01T01:00:00Z'))
  await card.click()
  await expect(page.getByRole('dialog', { name: 'Preparing level', exact: true })).toHaveCount(0)
  await page.clock.runFor(160)
  await expect(page.locator('.jumping-state')).toHaveText('Waking up')
  await page.keyboard.press('Escape')
  await page.clock.runFor(5000)
  await page.getByRole('button', { name: /^Resume/ }).click()
  await page.clock.runFor(160)
  await expect(page.locator('.jumping-state')).toHaveText('Waking up')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Restart level', exact: true }).click()
  await page.clock.runFor(160)
  await expect(page.locator('.jumping-state')).toHaveText('Waking up')
  await page.screenshot({ path: info.outputPath('wake-awakening.png') })
  await page.setViewportSize({ width: 390, height: 844 }); await page.clock.runFor(16)
  await page.screenshot({ path: info.outputPath('wake-pod-portrait.png') })
  await page.setViewportSize({ width: 960, height: 600 })
  await page.clock.runFor(650)
  await page.screenshot({ path: info.outputPath('wake-pod-power.png') })
  await page.clock.runFor(1750)
  await page.screenshot({ path: info.outputPath('wake-pod-release.png') })
  await finishJumpingEntrance(page)
  await expect(page.getByRole('timer')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 }); await page.clock.runFor(64)
  await page.screenshot({ path: info.outputPath('wake-portrait.png') })
  await page.setViewportSize({ width: 1280, height: 800 }); await page.clock.runFor(64)
  await page.screenshot({ path: info.outputPath('wake-ready.png') })
  await page.setViewportSize({ width: 960, height: 600 }); await page.clock.runFor(16)
  await page.keyboard.down('ArrowRight')
  await page.keyboard.down('Space'); await page.clock.runFor(70); await page.keyboard.up('Space')
  await page.clock.runFor(1030)
  await page.clock.runFor(900)
  await page.screenshot({ path: info.outputPath('wake-energized.png') })
  await page.clock.runFor(3900); await page.keyboard.up('ArrowRight')
  await expect(page.getByRole('dialog', { name: 'Level complete', exact: true })).toBeVisible()
  await expect(page.locator('.jumping-result-targets')).toHaveCount(0)
  await expect(page.locator('.jumping-result-time')).toHaveCount(0)
  await expect(page.locator('.jumping-result-award')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Next level', exact: true })).toBeVisible()
  expect(await page.evaluate(id => JSON.parse(localStorage.getItem('arcade.jumping.completed.v1'))[id], wake.id)).toBe(true)
  expect(await page.evaluate(id => JSON.parse(localStorage.getItem('arcade.jumping.times.v1') ?? '{}')[id], wake.id)).toBeUndefined()
  await page.getByRole('button', { name: 'Level menu', exact: true }).click()
  await expect(card.getByText('Completed', { exact: true })).toBeVisible()
  await page.clock.resume()
  await page.reload()
  await expect(card.getByText('Completed', { exact: true })).toBeVisible()
})

test('charging bay, untimed mode, and optional conduit edit, undo, save and reopen in the studio', async ({ page }, info) => {
  // This full night-mode edit/undo/save/reload flow keeps its real rendering;
  // software Chromium on slower desktops needs more than a minute for it.
  test.setTimeout(120000)
  await useLevelFixtures(page, [wake]); await installBuiltInFixtures(page, { 'Wake.json': wake })
  await page.goto('/lab')
  await page.getByRole('button', { name: 'Level studio', exact: true }).click()
  await page.getByRole('button', { name: 'Library', exact: true }).click()
  await page.getByRole('button', { name: 'Open Wake.json', exact: true }).click()
  await expect(page.getByRole('application', { name: 'Level canvas' })).toHaveAttribute('aria-busy', 'false')
  await selectBuilderObject(page, 'trigger:0')
  const wires = page.getByRole('checkbox', { name: 'Show wall wiring', exact: true })
  await page.locator('summary[aria-label="Wall wiring"]').click()
  await expect(wires).toBeChecked()
  await wires.uncheck(); await expect(wires).not.toBeChecked()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await selectBuilderObject(page, 'trigger:0'); await page.locator('summary[aria-label="Wall wiring"]').click(); await expect(wires).toBeChecked()
  await page.getByRole('spinbutton', { name: 'Wire height', exact: true }).fill('260')
  await page.getByRole('spinbutton', { name: 'Wire height', exact: true }).press('Tab')
  await selectBuilderObject(page, 'entrance:0')
  await expect(page.getByRole('combobox', { name: 'Entrance style', exact: true })).toHaveText('Charging bay')
  await selectBuilderOption(page, 'Entrance style', 'door')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await selectBuilderObject(page, 'entrance:0')
  await expect(page.getByRole('combobox', { name: 'Entrance style', exact: true })).toHaveText('Charging bay')
  await page.getByRole('tab', { name: 'Level', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Untimed level', exact: true })).toBeChecked()
  await expect(page.getByRole('group', { name: 'Grade times (seconds)', exact: true })).toHaveCount(0)
  const saved = await saveTestLevel(page)
  expect(saved.level).toMatchObject({ timing: 'untimed', entrance: { kind: 'charging-bay' }, triggers: [{ showWires: true, wireHeight: 260 }] })
  await page.reload(); await reopenTestLevel(page, saved)
  await selectBuilderObject(page, 'trigger:0')
  await page.locator('summary[aria-label="Wall wiring"]').click()
  await expect(wires).toBeChecked()
  await expect(page.getByRole('spinbutton', { name: 'Wire height', exact: true })).toHaveValue('260')
  await page.screenshot({ path: info.outputPath('wall-wiring-studio.png') })
})
