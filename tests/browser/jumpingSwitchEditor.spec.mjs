import { test, expect } from './helpers/folderTest.mjs'
import { selectBuilderObject, selectBuilderOption, installTestFolder, useLevelFixtures, saveTestLevel, reopenTestLevel } from './helpers/jumpingLevels.mjs'
import { readLevelAsset } from '../helpers/jumping-fixtures.mjs'

async function openSwitches(page) {
  const level = readLevelAsset('switch-modes.json')
  level.triggers[0].w = 100
  await useLevelFixtures(page, [level]); await installTestFolder(page, { 'switches.json': level })
  await page.goto('/untitled-jumping-game')
  await page.getByRole('button', { name: 'Level studio', exact: true }).click()
  await page.getByRole('button', { name: 'Library', exact: true }).click()
  const local = page.getByRole('dialog').getByRole('button', { name: 'Local folder', exact: true })
  if (await local.count()) await local.click()
  await page.getByRole('button', { name: 'Choose folder', exact: true }).click()
  await page.getByRole('button', { name: 'Open switches.json', exact: true }).click()
  await expect(page.getByRole('application', { name: 'Level canvas' })).toHaveAttribute('aria-busy', 'false')
}

test('dedicated logic nodes wire, undo, duplicate and reopen without Power or Relay controls', async ({ page }, info) => {
  await openSwitches(page)
  const canvas = page.getByRole('application', { name: 'Level canvas' })
  await page.getByRole('button', { name: 'Logic relay', exact: true }).click()
  const bounds = await canvas.boundingBox()
  await canvas.click({ position: { x: bounds.width * .45, y: bounds.height * .35 } })
  await selectBuilderObject(page, 'logic-relay:0')
  await expect(page.getByRole('heading', { name: 'Logic relay 1', exact: true })).toBeVisible()
  const behavior = page.getByRole('group', { name: 'Switch behavior', exact: true })
  await expect(behavior.getByRole('checkbox', { name: 'Relay', exact: true })).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: /power/i })).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: 'Switch logic', exact: true })).toHaveText('OR')
  await selectBuilderOption(page, 'Switch logic', 'xor')
  await behavior.getByRole('checkbox', { name: 'Reversed', exact: true }).check()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await selectBuilderObject(page, 'logic-relay:0')
  await expect(behavior.getByRole('checkbox', { name: 'Reversed', exact: true })).not.toBeChecked()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await selectBuilderObject(page, 'logic-relay:0')
  await expect(behavior.getByRole('checkbox', { name: 'Reversed', exact: true })).toBeChecked()
  await page.getByRole('group', { name: 'Switched by', exact: true }).getByRole('checkbox', { name: 'Pressure plate 1', exact: true }).check()
  await page.getByRole('group', { name: 'Activates', exact: true }).getByRole('checkbox', { name: 'Spotlight 1', exact: true }).check()
  await behavior.scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('logic-relay-inspector.png') })
  await selectBuilderObject(page, 'light:0')
  await expect(page.getByRole('group', { name: 'Switched by', exact: true }).getByRole('checkbox', { name: 'Logic relay 1', exact: true })).toBeChecked()
  await selectBuilderObject(page, 'logic-relay:0')
  await page.getByRole('button', { name: 'Duplicate', exact: true }).click()
  const saved = await saveTestLevel(page)
  expect(saved.level.logicRelays).toHaveLength(2)
  for (const relay of saved.level.logicRelays) {
    expect(relay).toMatchObject({ switchLogic: 'xor', switchReversed: true, targets: ['lamp'] })
    expect(relay.power).toBeUndefined(); expect(relay.relay).toBeUndefined()
  }
  expect(saved.level.logicRelays[0].id).not.toBe(saved.level.logicRelays[1].id)
  expect(saved.level.triggers[0].targets).toContain(saved.level.logicRelays[0].id)
  await page.reload(); await reopenTestLevel(page, saved)
  await selectBuilderObject(page, 'logic-relay:0')
  await expect(page.getByRole('combobox', { name: 'Switch logic', exact: true })).toHaveText('XOR')
  await expect(behavior.getByRole('checkbox', { name: 'Reversed', exact: true })).toBeChecked()
  await expect(page.getByRole('group', { name: 'Activates', exact: true }).getByRole('checkbox', { name: 'Spotlight 1', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Delete object', exact: true }).click()
  await selectBuilderObject(page, 'trigger:0')
  await expect(page.getByRole('group', { name: 'Activates', exact: true }).getByRole('checkbox', { name: 'Logic relay 1', exact: true })).not.toBeChecked()
  const deleted = await saveTestLevel(page)
  expect(deleted.level.triggers[0].targets).not.toContain(saved.level.logicRelays[0].id)
})

